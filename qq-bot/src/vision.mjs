/**
 * 识图（把画面转成文字）用的提示词与纪律。
 *
 * ## 为什么单独抽出来
 *
 * 2026-10-09 用户报「识图有点不准，danking 没认出来」。查日志看到的是：
 *
 * ```
 * 12:14:49 它：「这是 Uzi 啊，简自豪，RNG 的 ADC。」   ← 自信地认错人（其实是主播 Danking）
 * 12:15:21 用户再说一遍才收回：「我上一句说得太满了…不能百分百确定」
 * ```
 *
 * 真因不是"看不清"，而是**我们的提示词在鼓励它认人**：旧版写着
 * 「如果认得出是哪个动漫/游戏角色、**明星**或知名作品，**直接说出名字**」。
 * 视觉模型对"网红/选手"这类脸基本靠猜，一鼓励就变成**自信的错误**。
 *
 * 现在的口径（三条）：
 *  1. **先抄文字**：画面里的 ID / 水印 / 队标 / 比分 / 游戏 UI 是最可靠的线索，必须原样抄下来；
 *  2. **别给人脸安名字**：真人不认识就说不认识；有把握的角色/作品只能说「大概是XX」；
 *  3. 拿不准一律写「不确定」——宁可说不知道，也别给一个像样的错答案。
 */

/**
 * 送给视觉模型的提示词。
 *
 * ⚠️ **2026-10-11 加 `question`**（用户问「识图有时候感觉不准，是模型原因还是什么」）：
 * 查下来有两条我们自己的问题：① 发给模型的是**原图**（没压过，8MB 上限）、模型也是同一个 ——
 * 所以"看不清"主要来自**模型本身**（`deepseek-chat` 不是专门的视觉模型：
 * **读文字/UI 挺准，认人脸/角色很弱**，日志里的实测输出也印证）；② 但我们的提示词
 * **是通用描述**，不知道他到底想问什么 —— 这条能改。现在把他的原话带进来：
 * **优先回答他关心的那个点**，其余一句带过。
 */
export function visionPrompt(question = '') {
  const q = String(question ?? '').trim().slice(0, 120);
  return (
    (q ? `他发这张图时问的是：「${q}」——**优先照这个点看**（他问是谁就给能核对的线索、他问写的什么就把字抄全），其余一句带过。\n` : '') +
    '用中文描述这张图，按下面的优先级给"**能核对的东西**"：\n' +
    '① **画面里的文字**（ID、水印、队标、比分、弹幕、游戏 UI）——有就**原样抄下来**，这是最可靠的线索；\n' +
    /**
     * ⚠️ **② 物体识别**（2026-10-12 用户要求：「要能识别物体」）。
     * 之前这版只强调"抄文字 + 主体在做什么"，**没明确要求认东西** ——
     * 他发一张实物照片（零食、器材、零件、植物、宠物…）时，她只会泛泛说"一个东西"。
     * 现在单列一条，并要求：**能确定的说到点上**（是什么、牌子/型号/材质/用途/状态），
     * 拿不准就写"不确定" —— 跟人脸同一条纪律：**宁可说不知道，也别给一个像样的错答案**。
     */
    '② **画面里的物体**：是什么东西、**包装/机身/铭牌上的字样与牌子型号**、材质、用途、状态（新的/旧的/拆开的/用过的）——\n' +
    '　 有把握就**说到点上**（「一包某某牌的原味薯片」「像是 3D 打印机的喷嘴」「无线鼠标的接收器」），别只说"一个物品"；\n' +
    '　 拿不准就写「不确定」或「像是……」，**不要凭感觉编一个名字**；\n' +
    '③ 主体在干什么、穿什么、在什么场景；④ 大致氛围或用途。\n' +
    '**不要给人脸安名字**：真人尤其是网红/选手/明星，你不知道是谁就说不知道（可以说"男性/女性、大约年纪、在做什么"）。' +
    /**
     * ⚠️ **2026-10-14：动漫/游戏角色改成"候选名 + 确信度"**（用户报「能不能把动漫角色识图成功率拉高些」）。
     *
     * 为什么这么改：老口径是"**只有非常有把握**才可以说" ⇒ 实测模型干脆**不提角色** ✗
     * （他真机那张少女前线的 3D 渲染，老提示词只输出"3D 渲染的动漫风女性…" ✓，一个字没认）。
     * 而加上"给候选 + 标确信度"之后，同一个模型会输出
     * 「像是 小春（蔚蓝档案）· **确信度 低**」✓ —— 虽然猜错了 ✗，但它**如实自报了低确信** ✓✓。
     * 这正是我们要的：**有信息量、又不会变成自信的错误** ✓（最后一句仍然禁止"编"✓）。
     */
    '**动漫/游戏角色**：如果你觉得像某个已知角色，给出「候选名（作品名）」并**标注「确信度：高/中/低」**，' +
    '例如「像是 可露凯（少女前线）· 确信度 中」；\n' +
    '　 确信度**低**也**要写出来**（这比不提有用得多 ✓），但**不许把低确信写成肯定句** ✗；' +
    '　 实在没线索就写「认不出」——**宁可说认不出，也不要编一个像样的错答案**。\n' +
    '拿不准的一律写「不确定」。\n' +
    '120 字以内，直接说内容，不要客套话，不要「这张图片展示了」这种开头。'
  );
}

/** 把描述塞进对话时附在后面的那句纪律（防止它写回复时又自信认人）。 */
export function imageDisciplineNote() {
  return '（认人要有把握：没把握就说"看不出来"，只报你看到的特征和文字。**别给脸安名字**。）';
}

/**
 * **发前筛图那道闸的提示词**（2026-10-10 抽成纯函数，见下）。
 *
 * ## 为什么要抽出来 + 为什么要带场景
 *
 * 2026-10-10 13:34 用户实测：他说「找找胡桃的 r18 图」，
 * 私聊里拿到的两张候选里**被筛掉一张本来完全可以发**（`artworks/150672152`，
 * 标签 R-18 / 胡桃 / 原神，xRestrict=1）。旧提示词只问
 * 「这张图能不能作为『胡桃』的搜索结果发出去」——**一个字都没提这是私聊、R-18 是允许的**，
 * 视觉模型看到露骨内容自然就往"不合适"倒（这正是本文件顶上那条
 * 「禁止压倒许可：模型遇到模糊一律往禁止那边倒」）。
 *
 * 所以现在**把场景明写进提示词**：
 *   - **主人的私聊** → `allowR18:true`：R-18 就是允许的，**不许因为露骨而否决**，只判相关性；
 *   - 其它任何地方（群、别人私聊）→ 分级也要考虑，露骨/R-18 一律不合适。
 *
 * @param {{query?:string, allowR18?:boolean, tags?:string[], xRestrict?:number, exclude?:string[]}} opts
 *        `exclude` = 用户明确说**不要**的标签（「不要 r18」）—— 它对**没有标签可比**的那条路
 *        （Bing 搜来的图）是唯一能拦住的手段，所以要交给"看图的"去判。
 */
export function screenAsk({ query = '', allowR18 = false, tags = [], xRestrict = 0, exclude = [] } = {}) {
  const word = String(query ?? '').slice(0, 30);
  const scene = allowR18
    ? '**场景：我和主人的私聊 —— 这里 R-18 / 露骨内容是允许的**。' +
      '所以**不要因为画面露骨、穿着少、有性暗示或 R-18 标签而判不合适**，那是正常的搜索结果。' +
      '你只需要判**相关性**。'
    : '**场景：群聊或别人的私聊 —— 这里不许出现露骨内容**。' +
      '除了相关性，**分级也要一起考虑**：露骨 / R-18 / R-18G 一律判不合适。';
  /**
   * ⚠️ **2026-10-10 17:0x 用户要求「我说不要【标签】发来的图，就不要带那个标签的」** ——
   * 用户点名"不要"的，**优先级高于上面的场景话术**（他自己说的算）。
   */
  const ex = (Array.isArray(exclude) ? exclude : []).map((t) => String(t).trim()).filter(Boolean);
  const exAdult = ex.some((t) => /^r-?18g?$|^r18g?$/i.test(t));
  const exOthers = ex.filter((t) => !/^r-?18g?$/i.test(t));
  const forbid = [];
  if (exAdult) forbid.push('**主人明确说了不要 R-18 内容** —— 这张只要露骨 / 有明显性描写，一律判**不合适**。');
  if (exOthers.length) {
    forbid.push(`主人明确说了**不要**：${exOthers.map((t) => `「${t}」`).join('、')}。画面明显属于这类就判**不合适**。`);
  }
  // 作品自带的标签/分级只当**参考事实**给出，不额外下结论（免得又把它推向禁止）。
  const facts = [];
  if (Array.isArray(tags) && tags.length) facts.push(`作品自带标签：${tags.slice(0, 8).join(' / ')}`);
  if (Number(xRestrict) >= 1) facts.push(`pixiv 分级字段 xRestrict=${Number(xRestrict)}（1=R-18、2=R-18G）`);
  return (
    `这张图能不能作为"${word}"的搜索结果发出去？\n` +
    `${scene}\n` +
    (forbid.length ? `${forbid.join('\n')}\n` : '') +
    '**合适** = 画面主体就是这个词所指的**角色/人物/景物本身**（插画、照片、截图里的角色特写）。\n' +
    '**不合适** = ①攻略/教程/评测的截图；②网页或 App 界面截图；③以文字、表格、数据为主的图；' +
    '④装备/属性/技能面板、流程图、地图；⑤广告、二维码、水印墙；⑥太糊看不清；⑦跟这个词没关系。\n' +
    (facts.length ? `${facts.join('；')}\n` : '') +
    '**这样回答**：第一行只写两个字「合适」或「不合适」，第二行用**不超过 20 个字**说明理由' +
    '（理由要具体，比如「主体就是胡桃」「这是攻略截图」），不要写别的。'
  );
}

/**
 * **解析筛图的回答**（纯函数：`{ ok, reason }`）。
 *
 * ⚠️ 2026-10-10 用户第三个问题：「筛图只回合适/不合适、没有理由」→ 日志里只看到
 * 「筛掉一张（不合适）」，**没法复盘为什么被筛掉**（这次是用户自己反查作品标签才看出来的）。
 * 所以现在让它**多回一句理由**，这里负责把那句抠出来，并保持**判定语义和以前完全一致**
 * （`合适` 且不含 `不合适` 才算放行），免得顺手改出个"什么都放行"的新洞。
 */
export function parseScreenVerdict(text) {
  const t = String(text ?? '').replace(/\s+/g, ' ').trim();
  const ok = /合适/.test(t) && !/不合适/.test(t);
  const reason = t
    .replace(/不合适|合适/g, ' ')
    .replace(/^[\s｜|:：,，。.、\-—]+/, '')
    .replace(/^理由[\s:：]*/, '')
    .trim()
    .slice(0, 30);
  return { ok, reason };
}
